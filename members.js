const members = GROUPS.flatMap(group =>

  group.names
    .trim()
    .split("\n")
    .map((name, index) => {

      const id =
        group.start + index;

      /*
        274番・絢咲羽蘭だけ
        JPG。
        それ以外は組ごとの拡張子。
      */

      const extension =
        id === 274
          ? "JPG"
          : group.ext;

      return {

        id: id,

        name:
          name.trim(),

        group:
          group.name,

        groupKey:
          group.key,

        color:
          group.color,

        image:
          `images/${group.key}/${id}.${extension}`

      };

    })

);


